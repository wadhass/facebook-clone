function readLanguage() {
  const savedLanguage = window.localStorage.getItem('qavero-language')
  return languageOptions.some(({ code }) => code === savedLanguage) ? savedLanguage : 'en'
}

function readLowDataPreference() {
  const savedPreference = window.localStorage.getItem('qavero-low-data')
  if (savedPreference !== null) return savedPreference === 'true'
  return navigator.connection?.saveData === true
}

export function PreferencesProvider({ children }) {
  const [language, setLanguage] = useState(readLanguage)
  const [lowData, setLowData] = useState(readLowDataPreference)

  useEffect(() => {
    window.localStorage.setItem('qavero-language', language)
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
  }, [language])

  useEffect(() => {
    window.localStorage.setItem('qavero-low-data', String(lowData))
  }, [lowData])

  const value = useMemo(() => ({
    language,
    setLanguage,
    languages: languageOptions,
    lowData,
    setLowData,
    t: (key) => translations[language]?.[key] ?? key,
  }), [language, lowData])

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>
}
